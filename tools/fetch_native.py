"""Native state ranges for every species in the atlas, from Kew's World Checklist
of Vascular Plants (WCVP) via the GBIF API.

WCVP marks each Australian state as native or INTRODUCED. WCVP treats the ACT as
part of New South Wales, so ACT is counted native wherever NSW is.

Writes app/data/native_ranges.js:
  window.NATIVE_RANGES = {"Eucalyptus pauciflora": {"states": [...], "other": [...]}}
"other" lists native places outside the states (e.g. Norfolk Is.). Species
GBIF/WCVP cannot match are left out (the app then falls back to ALA records).
Responses are cached in tools/cache/ so re-runs are quick.
"""
import json
import re
import sys
import urllib.parse
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fetch_ala import fetch  # same cached, retrying HTTP helper

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "data" / "native_ranges.js"
REGIONS = {
    "new south wales": "NSW", "victoria": "VIC", "queensland": "QLD", "western australia": "WA",
    "south australia": "SA", "tasmania": "TAS", "northern territory": "NT",
}
OTHER = {"lord howe i.": "Lord Howe Island", "norfolk is.": "Norfolk Island", "coral sea is.": "Coral Sea Islands"}


def species_names():
    html = (ROOT / "app" / "index.html").read_text(encoding="utf-8")
    curated = re.findall(r'\{ sci: "([^"]+)"', html)
    ala_js = (ROOT / "app" / "data" / "ala_species.js").read_text(encoding="utf-8")
    ala = [r["sci"] for r in json.loads(ala_js[ala_js.index("["):ala_js.rindex("]") + 1])]
    return list(dict.fromkeys(curated + ala))


def native_range(sci):
    m = fetch("https://api.gbif.org/v1/species/match?" + urllib.parse.urlencode(
        {"name": sci, "kingdom": "Plantae", "rank": "SPECIES", "strict": "true"}))
    if m.get("matchType") != "EXACT" or m.get("rank") != "SPECIES":
        return None
    key = m.get("acceptedUsageKey") or m["usageKey"]
    d = fetch(f"https://api.gbif.org/v1/species/{key}/distributions?limit=300")
    states, other, seen_wcvp = set(), set(), False
    for x in d.get("results", []):
        if "World Checklist of Vascular Plants" not in (x.get("source") or ""):
            continue
        seen_wcvp = True
        place = (x.get("locality") or "").strip().lower()
        if (x.get("establishmentMeans") or "NATIVE").upper() != "NATIVE":
            continue  # INTRODUCED / naturalised
        if place in REGIONS:
            states.add(REGIONS[place])
        elif place in OTHER:
            other.add(OTHER[place])
    if not seen_wcvp:
        return None
    if "NSW" in states:
        states.add("ACT")  # WCVP includes the ACT within New South Wales
    order = ["NSW", "VIC", "QLD", "WA", "SA", "TAS", "NT", "ACT"]
    return {"states": [s for s in order if s in states], "other": sorted(other)}


def main():
    names = species_names()
    print(f"{len(names)} species", flush=True)
    result, missing = {}, []

    def work(sci):
        try:
            return sci, native_range(sci)
        except Exception as e:
            print(f"  error {sci}: {e}", flush=True)
            return sci, None

    with ThreadPoolExecutor(max_workers=4) as pool:
        for i, (sci, rng) in enumerate(pool.map(work, names), 1):
            if rng is None:
                missing.append(sci)
            else:
                result[sci] = rng
            if i % 250 == 0:
                print(f"  {i}/{len(names)}", flush=True)

    OUT.write_text(
        "// Generated by tools/fetch_native.py — native ranges from Kew's World Checklist of\n"
        "// Vascular Plants (WCVP) via GBIF. ACT counted native wherever NSW is.\n"
        "window.NATIVE_RANGES = " + json.dumps(result, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8")
    (ROOT / "tools" / "native_missing.json").write_text(json.dumps(missing, indent=1), encoding="utf-8")
    print(f"DONE: {len(result)} with native ranges, {len(missing)} unmatched", flush=True)


if __name__ == "__main__":
    if len(sys.argv) > 1:  # quick test: python fetch_native.py "Name one" "Name two"
        for n in sys.argv[1:]:
            print(n, native_range(n))
    else:
        main()
