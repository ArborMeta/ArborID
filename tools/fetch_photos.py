"""Download one openly-licensed iNaturalist photo per species into app/photos/.

Only exact scientific-name matches are accepted, so a species never gets a
photo of a different plant. Writes app/photos/photos.js (window.BUNDLED_PHOTOS).
Re-runnable: species already downloaded are skipped.
"""
import json
import re
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PHOTOS = ROOT / "app" / "photos"
MANIFEST = PHOTOS / "photos.js"
UA = {"User-Agent": "ArborID/1.0 (personal botanical desktop app)"}


def get_json(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def download(url, dest):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=60) as r:
        dest.write_bytes(r.read())


def licensed_photo(taxon):
    """Prefer the default photo; fall back to any CC-licensed taxon photo."""
    dp = taxon.get("default_photo")
    if dp and dp.get("license_code"):
        return dp
    time.sleep(1)
    full = get_json(f"https://api.inaturalist.org/v1/taxa/{taxon['id']}")["results"][0]
    for tp in full.get("taxon_photos", []):
        p = tp.get("photo", {})
        if p.get("license_code"):
            return p
    return None


def main():
    species = json.loads((ROOT / "tools" / "species.json").read_text(encoding="utf-8"))
    PHOTOS.mkdir(parents=True, exist_ok=True)
    manifest = {}
    if MANIFEST.exists():
        m = re.search(r"=\s*(\{.*\});?\s*$", MANIFEST.read_text(encoding="utf-8"), re.S)
        manifest = json.loads(m.group(1)) if m else {}

    names = sorted({s["sci"] for s in species if " var. " not in s["sci"]})
    missing = []
    for i, sci in enumerate(names, 1):
        if sci in manifest:
            continue
        time.sleep(1)  # iNaturalist asks for <= 1 request/second
        try:
            q = urllib.parse.quote(sci)
            res = get_json(f"https://api.inaturalist.org/v1/taxa?q={q}&per_page=10")["results"]
            taxon = next((t for t in res if t["name"].lower() == sci.lower()), None)
            photo = licensed_photo(taxon) if taxon else None
            if not photo:
                missing.append((sci, "no exact taxon" if not taxon else "no licensed photo"))
                print(f"[{i}/{len(names)}] --  {sci}")
                continue
            url = photo.get("medium_url") or photo["url"].replace("square", "medium")
            fname = re.sub(r"[^A-Za-z0-9]+", "_", sci).strip("_") + ".jpg"
            time.sleep(1)
            download(url, PHOTOS / fname)
            manifest[sci] = {
                "file": f"photos/{fname}",
                "attr": photo.get("attribution", ""),
                "license": photo["license_code"].upper(),
                "source": f"https://www.inaturalist.org/taxa/{taxon['id']}",
                "common": taxon.get("preferred_common_name", ""),
            }
            print(f"[{i}/{len(names)}] OK  {sci}")
        except Exception as e:  # network hiccup: leave for a re-run
            missing.append((sci, f"error: {e}"))
            print(f"[{i}/{len(names)}] ERR {sci}: {e}")

    MANIFEST.write_text(
        "// Generated by tools/fetch_photos.py — iNaturalist photos, see attr/license.\n"
        "window.BUNDLED_PHOTOS = " + json.dumps(manifest, indent=1, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    (ROOT / "tools" / "missing_photos.json").write_text(json.dumps(missing, indent=1), encoding="utf-8")
    print(f"\nPhotos: {len(manifest)}  Missing: {len(missing)}")


if __name__ == "__main__":
    main()
