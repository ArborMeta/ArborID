"""Give species that have no main (card) photo a profile picture from their sorted photos.

For each species with no bundled photo (no ALA default image and no iNaturalist photo),
pick the most confident photo whose main category is Tree; failing that Flowers,
Leaves, Fruit & seeds, then Bark. The thumbnail is downloaded into app/photos/profile/
so cards work offline, and app/data/profile_photos.js maps species -> photo + credit.

Run after build_app_data.py:  python build_profile_photos.py
"""
import json
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
APP = ROOT / "app"
OUT_DIR = APP / "photos" / "profile"
OUT_JS = APP / "data" / "profile_photos.js"
UA = {"User-Agent": "AusTreeAtlas/1.0 (personal botanical desktop app)"}
PREFERENCE = ["t", "f", "l", "s", "b"]   # Tree, Flowers, Leaves, Fruit & seeds, Bark


def load(path, var):
    s = path.read_text(encoding="utf-8")
    i = s.index("window." + var)
    s = s[s.index("=", i) + 1:]
    return json.loads(s[:s.rindex(";")])


def download(image_id, dest):
    i = image_id
    for url in (f"https://images-assets.ala.org.au/store/{i[-1]}/{i[-2]}/{i[-3]}/{i[-4]}/{i}/thumbnail",
                f"https://images.ala.org.au/image/{i}/thumbnail"):
        for attempt in range(3):
            try:
                with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
                    dest.write_bytes(r.read())
                return True
            except Exception:
                time.sleep(1 + attempt)
    return False


def main():
    ala = load(APP / "data" / "ala_species.js", "ALA_SPECIES")
    inat = load(APP / "photos" / "photos.js", "BUNDLED_PHOTOS")
    pc = load(APP / "data" / "photo_categories.js", "PHOTO_CATS")
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    # Herbarium specimen sheets make poor profile pictures; use them only as a last resort.
    # (Sources come from full_results.jsonl when it is present.)
    herbarium = set()
    results_file = Path(__file__).resolve().parent / "full_results.jsonl"
    if results_file.exists():
        for line in results_file.read_text(encoding="utf-8").splitlines():
            for p in json.loads(line)["photos"]:
                if "herbarium" in p["src"].lower() or "avh" in p["src"].lower():
                    herbarium.add(p["id"])

    result, by_section, failed, from_herbarium = {}, {c: 0 for c in PREFERENCE}, [], 0
    for r in ala:
        sci = r["sci"]
        if r.get("photo") or sci in inat:
            continue
        rows = pc["species"].get(sci, [])   # already sorted by confidence, best first
        pick = None
        for pool in ([p for p in rows if p[0] not in herbarium], rows):   # field photos first
            for code in PREFERENCE:
                # main category first (cats[0]); a photo listed second for this part is a fallback
                pick = next((p for p in pool if p[1][0] == code), None) or next((p for p in pool if code in p[1]), None)
                if pick:
                    break
            if pick:
                break
        if not pick:
            continue
        from_herbarium += pick[0] in herbarium
        image_id, cats, ci, li = pick
        dest = OUT_DIR / f"{image_id}.jpg"
        if not dest.exists() and not download(image_id, dest):
            failed.append(sci)
            continue
        result[sci] = {
            "file": f"photos/profile/{image_id}.jpg",
            "large": f"https://images.ala.org.au/image/{image_id}/large",
            "attr": f"© {pc['creators'][ci]}",
            "license": pc["licenses"][li],
            "via": "Atlas of Living Australia",
            "section": code,
        }
        by_section[code] += 1

    # remove photos no longer used (e.g. after a re-run)
    used = {Path(v["file"]).name for v in result.values()}
    for f in OUT_DIR.glob("*.jpg"):
        if f.name not in used:
            f.unlink()

    OUT_JS.write_text(
        "// Generated by experiments/photo-sort/build_profile_photos.py — card photos for species\n"
        "// without a main photo, picked from their sorted ALA photos (Tree preferred).\n"
        "window.PROFILE_PHOTOS = " + json.dumps(result, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8")
    size = sum(f.stat().st_size for f in OUT_DIR.glob("*.jpg")) / 1e6
    print(f"{len(result)} profile photos ({size:.1f} MB) -> {OUT_JS}")
    print("taken from section:", {"Tree": by_section["t"], "Flowers": by_section["f"], "Leaves": by_section["l"],
                                  "Fruit & seeds": by_section["s"], "Bark": by_section["b"]})
    print(f"herbarium specimen photos used (no field photo available): {from_herbarium}")
    if failed:
        print("download failed:", failed)


if __name__ == "__main__":
    main()
