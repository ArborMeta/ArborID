"""Convert full_results.jsonl into app/data/photo_categories.js for the species page tabs.

Format (compact):
  window.PHOTO_CATS = {
    creators: ["Jane Smith", ...], licenses: ["CC-BY 4.0 (Int)", ...],
    species: { "Eucalyptus pauciflora": [["<ALA image id>", "fl", creatorIdx, licenseIdx], ...] }
  }
Category letters: f = Flowers, s = Fruit & seeds, l = Leaves, b = Bark, t = Whole tree.
Photos within a species are ordered by model confidence (best first).
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "app" / "data" / "photo_categories.js"
CODE = {"flower": "f", "fruit_seed": "s", "leaf": "l", "bark": "b", "whole_tree": "t"}

creators, licenses, ci, li = [], [], {}, {}
species = {}
counts = {k: 0 for k in CODE}
n_species_with = {k: 0 for k in CODE}

for line in (HERE / "full_results.jsonl").read_text(encoding="utf-8").splitlines():
    row = json.loads(line)
    items = []
    for p in sorted(row["photos"], key=lambda p: -p["score"]):
        cats = "".join(CODE[c] for c in p["cats"] if c in CODE)
        if not cats:
            continue
        if p["by"] not in ci:
            ci[p["by"]] = len(creators); creators.append(p["by"])
        if p["lic"] not in li:
            li[p["lic"]] = len(licenses); licenses.append(p["lic"])
        items.append([p["id"], cats, ci[p["by"]], li[p["lic"]]])
        for c in p["cats"]:
            counts[c] += 1
    if items:
        species[row["sci"]] = items
        for k, code in CODE.items():
            if any(code in it[1] for it in items):
                n_species_with[k] += 1

OUT.write_text(
    "// Generated by experiments/photo-sort/build_app_data.py — ALA photos sorted by plant part\n"
    "// with OpenCLIP ViT-H-14-378 (DFN-5B). Images load from images.ala.org.au; credits per photo.\n"
    "window.PHOTO_CATS = " + json.dumps({"creators": creators, "licenses": licenses, "species": species},
                                        ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8")
print(f"{len(species)} species with sorted photos -> {OUT} ({OUT.stat().st_size / 1e6:.1f} MB)")
print("photos per tab:", counts)
print("species with at least one photo in tab:", n_species_with)
